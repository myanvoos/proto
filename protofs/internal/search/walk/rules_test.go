func TestRulesMatchIgnoreCrate(t *testing.T) {
	for _, c := range ruleCases {
		got := matchNone
		if f := parseIgnore(t.Context(), []byte(c.rules), nil); f != nil {
			got = f.match(c.path, c.dir)
		}
		if got != c.want {
			t.Errorf("rules %q, path %q (dir=%v): got %d, want %d", c.rules, c.path, c.dir, got, c.want)
		}
	}
}
